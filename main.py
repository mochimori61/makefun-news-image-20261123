#!/usr/bin/env python3
"""THE GLOBE IN ONE DAY — entry program for akun20 (@mochimori0172).

This is the make.fun news-image-20261123 entry for the newspaper
"THE GLOBE IN ONE DAY": a straight front page summing up Monday
23 November 2026 in 40 stories, led by gold sliding to $3,538 an ounce
from its 2026 record.

The program is deliberately boring: it copies the bundled entry.png to
the output directory and refuses to do so if the file does not match
the exact byte count and SHA-256 recorded at build time. It imports
only hashlib, os and sys from the standard library — no imaging
library is needed because the picture is shipped, not regenerated.
"""

import hashlib
import os
import sys

EXPECTED_BYTES = 271120
EXPECTED_SHA256 = "048eef8eb5d523f868aa5870c6a09f5c76981f14f607c414740297cb7db59a8e"
HARD_LIMIT = 1048576  # the competition caps entries at 1 MiB
PNG_HEADER = b"\x89PNG\r\n\x1a\n"


def load_entry():
    """Read the bundled entry.png sitting next to this file."""
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "entry.png"), "rb") as handle:
        return handle.read()


def check_entry(data):
    """Fail loudly unless data is exactly the image that was built."""
    if not data.startswith(PNG_HEADER):
        sys.exit("entry.png is not a PNG file (bad 8-byte header)")
    if len(data) > HARD_LIMIT:
        sys.exit("entry.png is over the 1 MiB cap: %d bytes" % len(data))
    if len(data) != EXPECTED_BYTES:
        sys.exit(
            "entry.png has %d bytes, expected %d" % (len(data), EXPECTED_BYTES)
        )
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit("entry.png sha256 mismatch: %s" % digest)
    return digest


def check_dimensions(data):
    """Second, independent guard: the PNG IHDR must say 1024 x 1024.

    The byte count and hash already pin the file, but this check keeps
    the program honest if EXPECTED_* are ever regenerated by hand: the
    competition gate also rejects anything over 1024 pixels on a side,
    and the width/height live big-endian at bytes 16..24 of the file.
    """
    if len(data) < 24:
        sys.exit("entry.png too short to hold an IHDR chunk")
    width = int.from_bytes(data[16:20], "big")
    height = int.from_bytes(data[20:24], "big")
    if width != 1024 or height != 1024:
        sys.exit("entry.png is %dx%d, expected 1024x1024" % (width, height))


def main():
    data = load_entry()
    digest = check_entry(data)
    check_dimensions(data)
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, "entry.png")
    with open(target, "wb") as handle:
        handle.write(data)
    sys.stderr.write("wrote %s: %d bytes sha256=%s\n" % (target, len(data), digest))


if __name__ == "__main__":
    main()
